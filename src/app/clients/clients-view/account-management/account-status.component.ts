@Component({
  selector: 'mifosx-account-status',
  imports: [TranslateModule],
  template: `{{ key | translate }}`,
  changeDetection: ChangeDetectionStrategy.OnPush
})
export class AccountStatusComponent {
  @Input() code: string | number | null;
  private readonly translate = inject(TranslateService);
  get key(): string {
    const code = String(this.code ?? '');
    const key = Object.hasOwn(ACCOUNT_STATUS_KEYS, code) ? ACCOUNT_STATUS_KEYS[code] : 'labels.inputs.Unavailable';
    return this.translate.instant(key) === key ? 'labels.inputs.Unavailable' : key;
  }
}
